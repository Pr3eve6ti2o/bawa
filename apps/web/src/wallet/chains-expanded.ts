export interface ExpandedChainPriceSources {
  /** CoinGecko /coins/list id — present on every chain. */
  coingeckoId: string;
  /** CoinLore ticker id (top-2000 tickers), or null when absent. */
  coinloreId: string | null;
  /** Coinbase Exchange product id (e.g. 'ETH-USD'), or null when unlisted. */
  coinbaseProduct: string | null;
  /** DexScreener chain slug, or null when no pair was seen (see header). */
  dexScreenerChainId: string | null;
}

export interface ExpandedChainFacts {
  /** Stable chain key, unique across the expanded set. */
  key: string;
  displayName: string;
  /** Native token ticker/symbol. */
  symbol: string;
  /** Trust Wallet Core CoinType property name. */
  coinTypeName: string;
  /** Trust Wallet Core CoinType number. */
  coinType: number;
  /** Account-0 derivation path from Trust Wallet Core. */
  derivationPath: string;
  /** Derivation path with {account} / {index} placeholders. */
  derivationTemplate: string;
  /** CAIP-2 network identifier (mainnet only). */
  networkId: string;
  /** CAIP-19 native asset identifier (networkId + /slip44:<coin index>). */
  assetId: string;
  /** EVM chain id, or null for non-EVM chains. */
  evmChainId: number | null;
  /** Mainnet RPC endpoints, each verified live (see rpcEvidence). */
  rpcEndpoints: string[];
  /** Per-endpoint live-verification evidence, parallel to rpcEndpoints. */
  rpcEvidence: string[];
  explorerBaseUrl: string;
  /** Transaction URL with a {hash} placeholder (filecoin: {messageCid}, tezos: {opHash}). */
  explorerTxUrlPattern: string;
  /** True when a real transaction page was live-clicked (HTTP 200). */
  explorerTxLive: boolean;
  priceSources: ExpandedChainPriceSources;
  /** Trust Wallet Assets path (blockchains/<dir>/info/logo.png), or null. */
  iconPath: string | null;
  /** Raw GitHub URL for the logo at the pinned commit, or null. */
  iconUrl: string | null;
  /** Sources each chain was cross-checked against (at least two). */
  sources: string[];
  notes: string;
}

