export async function buildRegistry(options = {}) {
  const generatedAt = options.generatedAt ?? new Date().toISOString();
  const stamp = options.stamp ?? gitInfo();
  const warnings = [];
  const errors = [];

  const sources = await loadWalletSources();
  try {
    const { chains, expanded, tokens, tokenPrices, prices, priceFallbacks, dexPrices } = sources;
    const { chainAmountFormat, devnet, watchOnly } = sources;
    const capabilities = loadJson(CAPABILITIES_PATH, 'registry/capabilities.json');
    const priceFallbacksText = readFileSync(
      join(APP_DIR, 'src', 'wallet', 'price-fallbacks.ts'),
      'utf8',
    );
    const addressDetectionText = readFileSync(
      join(APP_DIR, 'src', 'wallet', 'address-detection.ts'),
      'utf8',
    );
    const coinbaseProducts = extractCoinbaseProducts(priceFallbacksText);
    const addressPatterns = extractAddressPatterns(addressDetectionText);

    const supportedChains = chains.SUPPORTED_CHAINS;
    const chainConfigs = chains.CHAINS;
    const expandedByKey = new Map(
      expanded.EXPANDED_CHAINS.map((entry) => [entry.key, entry]),
    );
    const chainSupport = capabilities.chainSupport ?? {};
    const coins = capabilities.coins ?? {};

    // --- set equalities -------------------------------------------------
    const setOf = (values) => new Set(values);
    const sameSet = (a, b) => a.size === b.size && [...a].every((v) => b.has(v));
    const supportedSet = setOf(supportedChains);
    if (!sameSet(supportedSet, setOf(Object.keys(chainConfigs)))) {
      errors.push('CHAINS keys do not match SUPPORTED_CHAINS');
    }
    if (!sameSet(supportedSet, setOf(Object.keys(prices.PRICE_IDS)))) {
      errors.push('PRICE_IDS keys do not match SUPPORTED_CHAINS');
    }
    if (!sameSet(supportedSet, setOf(Object.keys(chainAmountFormat.CHAIN_DECIMALS)))) {
      errors.push('CHAIN_DECIMALS keys do not match SUPPORTED_CHAINS');
    }
    if (!sameSet(supportedSet, setOf(Object.keys(chainSupport)))) {
      errors.push('capabilities.json chainSupport keys do not match SUPPORTED_CHAINS');
    }
    const expandedKeys = setOf(expanded.EXPANDED_CHAINS.map((entry) => entry.key));
    if (expanded.EXPANDED_CHAINS.length !== expandedKeys.size) {
      errors.push('EXPANDED_CHAINS has duplicate keys');
    }
    if (expanded.EXPANDED_CHAIN_COUNT !== expanded.EXPANDED_CHAINS.length) {
      errors.push(
        `EXPANDED_CHAIN_COUNT (${expanded.EXPANDED_CHAIN_COUNT}) does not match EXPANDED_CHAINS.length (${expanded.EXPANDED_CHAINS.length})`,
      );
    }
    if (![...expandedKeys].every((key) => supportedSet.has(key))) {
      errors.push('EXPANDED_CHAINS has keys outside SUPPORTED_CHAINS');
    }

    // --- coins-table mapping ---------------------------------------------
    const displayNames = new Map();
    const coinTypeNames = new Map();
    for (const id of supportedChains) {
      displayNames.set(id, chainConfigs[id].displayName);
      coinTypeNames.set(id, chainConfigs[id].coinTypeName);
    }
    const coinsMapping = mapCoinsToChains(coins, supportedChains, displayNames, coinTypeNames);
    const coinsByChain = new Map();
    for (const { chain, entry } of coinsMapping.byRegistryId.values()) {
      coinsByChain.set(chain, entry);
    }

    // --- per-chain assembly ----------------------------------------------
    const chainEntries = [];
    let rpcTotal = 0;
    let withExplorer = 0;
    let withTemplate = 0;
    let withAddressFormat = 0;
    let withTrustWalletCoinType = 0;
    let withCurve = 0;
    let withSecondPriceSource = 0;
    const coingeckoAloneChains = [];
    const evmChainCount = watchOnly.EVM_WATCH_CHAINS.length;

    for (const id of supportedChains) {
      const config = chainConfigs[id];
      const notes = [];
      const entry = {
        id,
        name: config.displayName,
        symbol: config.symbol,
        network: 'mainnet',
        coinType: null,
        assetSlip44: null,
        coinTypeName: config.coinTypeName,
        trustWalletCoinType: null,
        curve: null,
        evmChainId: config.evmChainId,
        networkId: config.networkId,
        assetId: config.assetId,
        profileId: config.profileId,
        addressFormat: null,
        derivationPath: null,
        derivationTemplate: null,
        decimals: chainAmountFormat.CHAIN_DECIMALS[id],
        rpcEndpoints: [...config.rpcEndpoints],
        explorerUrl: null,
        explorerTxUrlPattern: null,
        coingeckoId: prices.PRICE_IDS[id],
        priceSources: [...priceFallbacks.priceFallbackSourcesFor(id)],
        priceFallbackIds: {
          coinloreId: priceFallbacks.COINLORE_NATIVE_IDS[id] ?? null,
          coinbaseProduct: coinbaseProducts.get(id) ?? null,
          dexscreenerChainId: dexPrices.DEXSCREENER_CHAIN_FOR_CHAIN[id] ?? null,
          wrappedNativeContract: priceFallbacks.NATIVE_WRAPPED_TOKENS[id]?.contract ?? null,
          wrappedNativeDexChain: priceFallbacks.NATIVE_WRAPPED_TOKENS[id]?.dexChain ?? null,
        },
      };

      // Derivation: reconstruct the template from pathFor and verify it.
      const template = reconstructDerivationTemplate(config.pathFor);
      entry.derivationPath = config.pathFor(0, 0);
      // The chain's registered SLIP-44 number, from its assetId. This is
      // NOT always the derivation coin: the five curated EVM chains below
      // derive on the Ethereum path (coin 60) while their assetId carries
      // their own registered number (BSC 714, Polygon 966, Avalanche
      // 9000, Celo 527, Fantom 250). Both facts are real, so both are
      // emitted (coinType = derivation coin, assetSlip44 = registered
      // number) and the difference is noted, never papered over.
      entry.assetSlip44 = slip44FromAssetId(config.assetId);
      if (entry.assetSlip44 === null) {
        errors.push(`${id}: assetId ${config.assetId} has no slip44 segment`);
      }
      if (template === null) {
        notes.push(ED25519_NO_TEMPLATE_NOTE);
      } else {
        entry.derivationTemplate = template;
        withTemplate += 1;
        entry.coinType = slip44FromTemplate(template);
        if (
          entry.assetSlip44 !== null &&
          entry.coinType !== null &&
          entry.coinType !== entry.assetSlip44
        ) {
          notes.push(
            `Derives on the Ethereum path (coin 60); the chain's registered SLIP-44 number in assetId is ${entry.assetSlip44}.`,
          );
        }
      }
      if (entry.coinType === null) {
        // Ed25519 chains: the template is null, but the account-0 path
        // still carries the coin — read it from the assetId.
        entry.coinType = slip44FromAssetId(config.assetId);
      }

      // Trust Wallet Core coin number + curve: the expanded facts carry
      // the number for all 65 expanded chains; the coins table carries
      // both for the 57 mapped coins (which covers all 22 curated
      // chains). Where both exist they must agree.
      const expandedEntry = expandedByKey.get(id);
      const coinsEntry = coinsByChain.get(id);
      if (expandedEntry !== undefined) {
        entry.trustWalletCoinType = expandedEntry.coinType;
      }
      if (coinsEntry !== undefined) {
        if (
          entry.trustWalletCoinType !== null &&
          entry.trustWalletCoinType !== coinsEntry.coinId
        ) {
          errors.push(
            `${id}: Trust Wallet coin ${entry.trustWalletCoinType} (chains-expanded.ts) disagrees with coins table ${coinsEntry.coinId}`,
          );
        }
        entry.trustWalletCoinType = coinsEntry.coinId;
        entry.curve = coinsEntry.curve ?? null;
        if (chainAmountFormat.CHAIN_DECIMALS[id] !== coinsEntry.decimals) {
          errors.push(
            `${id}: decimals ${chainAmountFormat.CHAIN_DECIMALS[id]} (CHAIN_DECIMALS) disagree with coins table ${coinsEntry.decimals}`,
          );
        }
      }
      if (entry.trustWalletCoinType !== null) withTrustWalletCoinType += 1;
      if (entry.curve !== null) {
        withCurve += 1;
      } else {
        notes.push(
          'No curve recorded in source (registry/capabilities.json coins has no entry for this chain).',
        );
      }

      // Explorer: the live history base first, else the expanded facts.
      if (config.historyExplorerBase !== undefined) {
        entry.explorerUrl = config.historyExplorerBase;
      }
      if (expandedEntry !== undefined) {
        if (entry.explorerUrl !== null && entry.explorerUrl !== expandedEntry.explorerBaseUrl) {
          errors.push(
            `${id}: explorer ${entry.explorerUrl} (chains.ts historyExplorerBase) disagrees with ${expandedEntry.explorerBaseUrl} (chains-expanded.ts)`,
          );
        }
        if (entry.explorerUrl === null) entry.explorerUrl = expandedEntry.explorerBaseUrl;
        entry.explorerTxUrlPattern = expandedEntry.explorerTxUrlPattern;
        // Cross-checks against the expanded facts.
        if (prices.PRICE_IDS[id] !== expandedEntry.priceSources.coingeckoId) {
          errors.push(
            `${id}: CoinGecko id ${prices.PRICE_IDS[id]} (PRICE_IDS) disagrees with ${expandedEntry.priceSources.coingeckoId} (chains-expanded.ts)`,
          );
        }
        if (
          (priceFallbacks.COINLORE_NATIVE_IDS[id] ?? null) !==
          expandedEntry.priceSources.coinloreId
        ) {
          errors.push(
            `${id}: CoinLore id ${priceFallbacks.COINLORE_NATIVE_IDS[id] ?? null} disagrees with ${expandedEntry.priceSources.coinloreId} (chains-expanded.ts)`,
          );
        }
        if (
          (coinbaseProducts.get(id) ?? null) !== expandedEntry.priceSources.coinbaseProduct
        ) {
          errors.push(
            `${id}: Coinbase product ${coinbaseProducts.get(id) ?? null} disagrees with ${expandedEntry.priceSources.coinbaseProduct} (chains-expanded.ts)`,
          );
        }
        const dexFromMap = dexPrices.DEXSCREENER_CHAIN_FOR_CHAIN[id] ?? null;
        const dexFromExpanded = expandedEntry.priceSources.dexScreenerChainId;
        if (dexFromMap !== null && dexFromExpanded !== null && dexFromMap !== dexFromExpanded) {
          errors.push(
            `${id}: DexScreener chain ${dexFromMap} (dex-prices.ts) disagrees with ${dexFromExpanded} (chains-expanded.ts)`,
          );
        }
        if (entry.priceFallbackIds.dexscreenerChainId === null && dexFromExpanded !== null) {
          entry.priceFallbackIds.dexscreenerChainId = dexFromExpanded;
        }
        if (
          entry.rpcEndpoints.length !== expandedEntry.rpcEndpoints.length ||
          ![...expandedEntry.rpcEndpoints].every((url) => entry.rpcEndpoints.includes(url))
        ) {
          errors.push(
            `${id}: RPC endpoints disagree between chains.ts and chains-expanded.ts`,
          );
        }
        if (entry.derivationTemplate !== null && entry.derivationTemplate !== expandedEntry.derivationTemplate) {
          errors.push(
            `${id}: derivation template ${entry.derivationTemplate} disagrees with ${expandedEntry.derivationTemplate} (chains-expanded.ts)`,
          );
        }
        if (entry.derivationPath !== expandedEntry.derivationPath) {
          errors.push(
            `${id}: account-0 path ${entry.derivationPath} disagrees with ${expandedEntry.derivationPath} (chains-expanded.ts)`,
          );
        }
      }
      if (entry.explorerUrl !== null) {
        withExplorer += 1;
      } else {
        notes.push('No explorer URL recorded in source for this chain.');
      }
      if (entry.explorerTxUrlPattern === null) {
        notes.push('No explorer transaction-URL pattern recorded in source for this chain.');
      }

      // Address format: the EVM 0x shape, else the detection table.
      if (watchOnly.isEvmChain(id)) {
        entry.addressFormat = {
          kind: 'evm',
          label: 'Ethereum (0x)',
          patterns: [addressPatterns.evmPattern],
          description: `0x-prefixed 40-hex-char address; the same address on all ${evmChainCount} EVM chains.`,
        };
        withAddressFormat += 1;
      } else if (addressPatterns.byChain.has(id)) {
        const rows = addressPatterns.byChain.get(id);
        entry.addressFormat = {
          kind: 'chain',
          label: rows[0].label,
          patterns: rows.map((row) => row.pattern),
          description: `${rows[0].label} address.`,
        };
        withAddressFormat += 1;
      } else {
        notes.push(
          'No address format recorded in source (not in address-detection.ts CHAIN_PATTERNS and not an EVM 0x chain).',
        );
      }

      // Price sources: CoinGecko is always first; record the alone set.
      if (entry.priceSources[0] !== 'CoinGecko') {
        errors.push(`${id}: price sources do not start with CoinGecko: ${entry.priceSources.join(', ')}`);
      }
      if (entry.priceSources.length > 1) {
        withSecondPriceSource += 1;
      } else {
        coingeckoAloneChains.push(id);
      }

      // RPC endpoints: https only, no duplicates, no empties.
      rpcTotal += entry.rpcEndpoints.length;
      if (entry.rpcEndpoints.length === 0) {
        errors.push(`${id}: no RPC endpoints`);
      }
      for (const url of entry.rpcEndpoints) {
        httpsUrl(url, `${id} rpcEndpoints`, errors);
      }
      if (new Set(entry.rpcEndpoints).size !== entry.rpcEndpoints.length) {
        errors.push(`${id}: duplicate RPC endpoints`);
      }
      if (entry.explorerUrl !== null) httpsUrl(entry.explorerUrl, `${id} explorerUrl`, errors);

      if (notes.length > 0) entry.notes = notes.join(' ');
      chainEntries.push(entry);
    }

    // --- testnets ----------------------------------------------------------
    const testnetEntries = [];
    for (const id of devnet.DEVNET_CHAINS) {
      const config = devnet.DEVNET_CHAIN_CONFIGS[id];
      const entry = {
        id,
        name: config.displayName,
        devnetName: config.devnetName,
        symbol: config.symbol,
        network: 'testnet',
        networkId: config.networkId,
        apiBaseUrl: config.apiBaseUrl,
        rpcUrl: config.rpcUrl ?? null,
        historyBaseUrl: config.historyBaseUrl ?? null,
        evmChainId: config.evmChainId ?? null,
        explorerTxUrl: config.explorerTxUrl,
        genesisHash: config.genesisHash ?? null,
        fallbackApiBaseUrl: config.fallbackApiBaseUrl ?? null,
      };
      httpsUrl(entry.apiBaseUrl, `${id} testnet apiBaseUrl`, errors);
      if (entry.rpcUrl !== null) httpsUrl(entry.rpcUrl, `${id} testnet rpcUrl`, errors);
      if (entry.fallbackApiBaseUrl !== null) {
        httpsUrl(entry.fallbackApiBaseUrl, `${id} testnet fallbackApiBaseUrl`, errors);
      }
      testnetEntries.push(entry);
    }

    // --- tokens ------------------------------------------------------------
    const tokenRequests = new Map(
      tokenPrices.tokenPriceRequests(tokens.DEFAULT_TOKENS).map((request) => [request.key, request]),
    );
    const tokenEntries = [];
    const tokenChains = new Set();
    for (const record of tokens.DEFAULT_TOKENS) {
      const notes = [];
      if (!supportedSet.has(record.chain)) {
        errors.push(`token ${record.symbol} on ${record.chain}: chain is not supported`);
      }
      tokenChains.add(record.chain);
      const key = tokens.tokenKey(record.chain, record.contract);
      const request = tokenRequests.get(key);
      const platform = tokens.COINGECKO_PLATFORM_FOR_CHAIN[record.chain] ?? null;
      if (platform === null) {
        notes.push(
          `No CoinGecko platform slug recorded for chain ${record.chain} (COINGECKO_PLATFORM_FOR_CHAIN has none).`,
        );
      }
      let priceFallback = null;
      if (record.chain === 'ton') {
        priceFallback = 'tonapi';
      } else if (dexPrices.DEXSCREENER_CHAIN_FOR_CHAIN[record.chain] !== undefined) {
        priceFallback = 'dexscreener';
      }
      const entry = {
        chain: record.chain,
        contract: record.contract,
        tokenKey: key,
        name: record.name,
        symbol: record.symbol,
        decimals: record.decimals,
        coingeckoId: record.coingeckoId,
        coingeckoPlatform: platform,
        verifiedSource: tokens.verificationSourceOf(record),
        priceSource: request?.kind === 'coingecko' ? 'coingecko' : (request?.kind ?? (record.coingeckoId !== null ? 'coingecko' : null)),
        priceFallback,
      };
      if (entry.priceSource === null) {
        errors.push(`token ${key}: no price source (no CoinGecko id and no fallback leg)`);
      }
      if (notes.length > 0) entry.notes = notes.join(' ');
      tokenEntries.push(entry);
    }
    if (new Set(tokenEntries.map((entry) => entry.tokenKey)).size !== tokenEntries.length) {
      errors.push('duplicate tokenKey in DEFAULT_TOKENS');
    }

    // --- live capabilities vs registry chainSupport (warning only) --------
    const capabilityMap = {
      create: (c) => c.derive.status === 'verified' && c.restore.status === 'verified',
      derive: (c) => c.derive.status === 'verified',
      restore: (c) => c.restore.status === 'verified',
      receive: (c) => c.receive.status === 'verified',
      balance: (c) => c.balance.status === 'verified',
      history: (c) => c.history.status === 'verified',
      'fee-quote': (c) => c['fee-quote'].status === 'verified',
      'plan-transfer': (c) => c['unsigned-plan'].status === 'verified',
      'local-sign': (c) => c['local-sign'].status === 'verified',
      'verify-signature': (c) => c['post-sign-verify'].status === 'verified',
    };
    for (const [op, checkFn] of Object.entries(capabilityMap)) {
      const live = supportedChains.filter((id) => checkFn(chainConfigs[id].capabilities));
      const registered = Object.keys(chainSupport).filter(
        (id) => chainSupport[id].operations[op] === 'IMPLEMENTED_AND_VERIFIED',
      );
      const liveOnly = live.filter((id) => !registered.includes(id));
      const registeredOnly = registered.filter((id) => !live.includes(id));
      if (liveOnly.length > 0 || registeredOnly.length > 0) {
        warnings.push(
          `capability drift on '${op}': live CHAINS has ${live.length}, chainSupport has ${registered.length}` +
            (liveOnly.length > 0 ? `; live-only: ${liveOnly.join(', ')}` : '') +
            (registeredOnly.length > 0 ? `; registry-only: ${registeredOnly.join(', ')}` : ''),
        );
      }
    }

    if (errors.length > 0) {
      fail(`cross-checks failed:\n${errors.join('\n')}`);
    }

    const chainsDoc = {
      generated: GENERATED_NOTICE,
      generator: GENERATOR_COMMAND,
      registry: 'chains',
      version: VERSION,
      generatedAt,
      sourceCommit: stamp.sourceCommit,
      sourceDirty: stamp.sourceDirty,
      chainCount: chainEntries.length,
      chains: chainEntries,
      testnets: testnetEntries,
      coverage: {
        chains: chainEntries.length,
        testnets: testnetEntries.length,
        rpcEndpoints: rpcTotal,
        chainsWithExplorer: withExplorer,
        chainsWithDerivationTemplate: withTemplate,
        chainsWithAddressFormat: withAddressFormat,
        chainsWithTrustWalletCoinType: withTrustWalletCoinType,
        chainsWithCurve: withCurve,
        chainsWithSecondPriceSource: withSecondPriceSource,
        coingeckoAloneChains,
      },
    };
    const tokensDoc = {
      generated: GENERATED_NOTICE,
      generator: GENERATOR_COMMAND,
      registry: 'tokens',
      version: VERSION,
      generatedAt,
      sourceCommit: stamp.sourceCommit,
      sourceDirty: stamp.sourceDirty,
      tokenCount: tokenEntries.length,
      tokens: tokenEntries,
      coverage: {
        tokens: tokenEntries.length,
        chains: tokenChains.size,
        withCoingeckoId: tokenEntries.filter((entry) => entry.coingeckoId !== null).length,
        withPriceFallback: tokenEntries.filter((entry) => entry.priceFallback !== null).length,
      },
    };
    return { chainsDoc, tokensDoc, warnings };
  } finally {
    sources.cleanup();
  }
}

