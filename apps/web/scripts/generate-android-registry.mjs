// Address shapes from address-detection.ts. CHAIN_PATTERNS is
// module-private; each row is [/^...$/, 'chain', 'Label'] except the
// Solana row, which builds its pattern from the BASE58 constant.
// Returns Map chain -> [{ pattern, label }]. The EVM 0x shape is the
// inline check in detectAddressFormat, extracted the same way.
export function extractAddressPatterns(addressDetectionText) {
  const base58Match = /const BASE58 = '([^']+)';/.exec(addressDetectionText);
  if (!base58Match) {
    fail('address-detection.ts: cannot find the BASE58 constant');
  }
  const base58 = base58Match[1];
  const tableStart = addressDetectionText.indexOf('const CHAIN_PATTERNS');
  if (tableStart === -1) fail('address-detection.ts: cannot find CHAIN_PATTERNS');
  const tableEnd = addressDetectionText.indexOf('];', tableStart);
  if (tableEnd === -1) fail('address-detection.ts: cannot find the end of CHAIN_PATTERNS');
  const table = addressDetectionText.slice(tableStart, tableEnd);
  const byChain = new Map();
  const addRow = (chain, pattern, label) => {
    try {
      new RegExp(pattern);
    } catch {
      fail(`address-detection.ts: CHAIN_PATTERNS row for '${chain}' is not a valid RegExp: /${pattern}/`);
    }
    if (!byChain.has(chain)) byChain.set(chain, []);
    byChain.get(chain).push({ pattern, label });
  };
  for (const match of table.matchAll(/\[\/\^?(.*?)\$\/, '([a-z0-9]+)', '([^']+)'\],/g)) {
    addRow(match[2], `^${match[1]}$`, match[3]);
  }
  // The Solana row is built from BASE58, not a literal: reconstruct it
  // exactly as the source builds it.
  const regExpRow = /\[new RegExp\(`\^\[\$\{BASE58\}\]\{(\d+),(\d+)\}\$`\), '([a-z0-9]+)', '([^']+)'\]/.exec(table);
  if (!regExpRow) {
    fail('address-detection.ts: cannot find the RegExp-built CHAIN_PATTERNS row');
  }
  addRow(
    regExpRow[3],
    `^[${base58}]{${regExpRow[1]},${regExpRow[2]}}$`,
    regExpRow[4],
  );
  const evmMatch = /if \(\/\^0x\[0-9a-fA-F\]\{40\}\$\/\.test\(input\)\)/.exec(addressDetectionText);
  if (!evmMatch) {
    fail('address-detection.ts: cannot find the EVM 0x shape check in detectAddressFormat');
  }
  return { byChain, evmPattern: '^0x[0-9a-fA-F]{40}$' };
}

