// Reconstruct the single derivation template from a chain's pathFor
// function by probing it: the account component is the one that moves
// between (0,0) and (1,0), the index component the one that moves
// between (0,0) and (0,1). The candidate template is then verified by
// re-evaluating it at five (account, index) pairs against pathFor.
// Returns the template, or null when no single template reproduces
// pathFor (Solana and TON: the Ed25519 scheme changes shape).
export function reconstructDerivationTemplate(pathFor) {
  const probe = (account, index) => pathFor(account, index);
  const p00 = probe(0, 0);
  const p10 = probe(1, 0);
  const p01 = probe(0, 1);
  const c00 = p00.split('/');
  const c10 = p10.split('/');
  const c01 = p01.split('/');
  if (c00.length !== c10.length || c00.length !== c01.length) return null;
  let accountPos = -1;
  let indexPos = -1;
  for (let i = 0; i < c00.length; i++) {
    if (c00[i] !== c10[i]) {
      if (accountPos !== -1) return null;
      accountPos = i;
    }
    if (c00[i] !== c01[i]) {
      if (indexPos !== -1) return null;
      indexPos = i;
    }
  }
  if (accountPos === -1) return null;
  const hardenedSuffix = (component) => (component.endsWith("'") ? "'" : '');
  const templateParts = [...c00];
  templateParts[accountPos] = `{account}${hardenedSuffix(c00[accountPos])}`;
  if (indexPos !== -1) {
    templateParts[indexPos] = `{index}${hardenedSuffix(c00[indexPos])}`;
  }
  const template = templateParts.join('/');
  for (const [account, index] of [[0, 0], [1, 0], [0, 1], [1, 2], [2, 3]]) {
    const expected = template
      .replace('{account}', String(account))
      .replace('{index}', String(index));
    if (expected !== probe(account, index)) return null;
  }
  return template;
}

// The SLIP-44 coin index a derivation template derives from: the
// component after the purpose (m/44'/<coin>/... or m/1852'/<coin>/...).
export function slip44FromTemplate(template) {
  const parts = template.split('/');
  if (parts.length < 3 || parts[0] !== 'm') {
    fail(`cannot read a SLIP-44 coin from derivation template '${template}'`);
  }
  const coin = parts[2].replace(/'$/, '');
  const value = Number(coin);
  if (!Number.isSafeInteger(value) || value < 0) {
    fail(`cannot read a SLIP-44 coin from derivation template '${template}'`);
  }
  return value;
}

function slip44FromAssetId(assetId) {
  const match = /\/slip44:(\d+)$/.exec(assetId);
  if (!match) fail(`cannot read a SLIP-44 coin from assetId '${assetId}'`);
  return Number(match[1]);
}

