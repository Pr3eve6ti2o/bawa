function writeJson(path, doc) {
  writeFileSync(path, `${JSON.stringify(doc, null, 2)}\n`, 'utf8');
}

function stripGeneratedAt(doc) {
  const copy = JSON.parse(JSON.stringify(doc));
  delete copy.generatedAt;
  return copy;
}

function validateDocs(chainsDoc, tokensDoc) {
  const chainsSchema = loadJson(CHAINS_SCHEMA_PATH, 'registry/schemas/chains.schema.json');
  const tokensSchema = loadJson(TOKENS_SCHEMA_PATH, 'registry/schemas/tokens.schema.json');
  const errors = [
    ...validateAgainstSchema(chainsDoc, chainsSchema).map((e) => `chains.json: ${e}`),
    ...validateAgainstSchema(tokensDoc, tokensSchema).map((e) => `tokens.json: ${e}`),
  ];
  if (errors.length > 0) {
    fail(`schema validation failed:\n${errors.join('\n')}`);
  }
}

function printSummary(chainsDoc, tokensDoc, warnings) {
  console.log(
    `generate-android-registry: ${chainsDoc.chainCount} chains, ` +
      `${chainsDoc.coverage.rpcEndpoints} RPC endpoints, ` +
      `${chainsDoc.testnets.length} testnets, ${tokensDoc.tokenCount} tokens`,
  );
  console.log(
    `generate-android-registry: coverage — explorer ${chainsDoc.coverage.chainsWithExplorer}/${chainsDoc.chainCount}, ` +
      `derivation template ${chainsDoc.coverage.chainsWithDerivationTemplate}/${chainsDoc.chainCount}, ` +
      `address format ${chainsDoc.coverage.chainsWithAddressFormat}/${chainsDoc.chainCount}, ` +
      `Trust Wallet coin ${chainsDoc.coverage.chainsWithTrustWalletCoinType}/${chainsDoc.chainCount}, ` +
      `curve ${chainsDoc.coverage.chainsWithCurve}/${chainsDoc.chainCount}, ` +
      `second price source ${chainsDoc.coverage.chainsWithSecondPriceSource}/${chainsDoc.chainCount}`,
  );
  for (const warning of warnings) {
    console.error(`generate-android-registry: WARNING — ${warning}`);
  }
}

function usage() {
  return (
    'usage: node apps/web/scripts/generate-android-registry.mjs [--check]\n' +
    '  (no flag)  rewrite registry/chains.json and registry/tokens.json\n' +
    '  --check    exit 1 when either file differs from the sources\n' +
    'Run from the repo root or from apps/web.'
  );
}

async function main(argv) {
  let check = false;
  for (const arg of argv) {
    if (arg === '--check') {
      check = true;
    } else if (arg === '--help' || arg === '-h') {
      console.log(usage());
      return 0;
    } else {
      console.error(`generate-android-registry: unrecognised argument '${arg}'\n${usage()}`);
      return 1;
    }
  }
  const { chainsDoc, tokensDoc, warnings } = await buildRegistry();
  validateDocs(chainsDoc, tokensDoc);
  if (!check) {
    writeJson(CHAINS_JSON_PATH, chainsDoc);
    writeJson(TOKENS_JSON_PATH, tokensDoc);
    console.log(
      `generate-android-registry: updated ${relative(REPO_DIR, CHAINS_JSON_PATH)} and ${relative(REPO_DIR, TOKENS_JSON_PATH)}`,
    );
    printSummary(chainsDoc, tokensDoc, warnings);
    return 0;
  }
  const diffs = [];
  for (const [path, doc] of [[CHAINS_JSON_PATH, chainsDoc], [TOKENS_JSON_PATH, tokensDoc]]) {
    if (!existsSync(path)) {
      diffs.push(`${relative(REPO_DIR, path)} is missing — regenerate`);
      continue;
    }
    let onDisk;
    try {
      onDisk = JSON.parse(readFileSync(path, 'utf8'));
    } catch (error) {
      diffs.push(`${relative(REPO_DIR, path)} is not valid JSON: ${error.message}`);
      continue;
    }
    if (JSON.stringify(stripGeneratedAt(onDisk)) !== JSON.stringify(stripGeneratedAt(doc))) {
      diffs.push(`${relative(REPO_DIR, path)} differs from the sources — regenerate with: ${GENERATOR_COMMAND}`);
    }
  }
  if (diffs.length > 0) {
    for (const diff of diffs) console.error(`generate-android-registry: drift: ${diff}`);
    return 1;
  }
  console.log('generate-android-registry: OK — registry/chains.json and registry/tokens.json match the sources');
  printSummary(chainsDoc, tokensDoc, warnings);
  return 0;
}

if (
  process.argv[1] &&
  import.meta.url === pathToFileURL(process.argv[1]).href
) {
  try {
    process.exitCode = await main(process.argv.slice(2));
  } catch (error) {
    console.error(error instanceof Error ? error.message : String(error));
    process.exitCode = 1;
  }
}
