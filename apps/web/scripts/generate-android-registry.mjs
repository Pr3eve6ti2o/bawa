// Collect the transitive closure of relative imports starting from the
// entry files. Bare specifiers (viem, react) are left alone — they
// resolve from apps/web/node_modules at import time.
export function collectClosure(entryFiles) {
  const seen = new Set();
  const queue = entryFiles.map((entry) => resolve(APP_DIR, entry));
  while (queue.length > 0) {
    const file = queue.pop();
    if (seen.has(file)) continue;
    seen.add(file);
    const text = readFileSync(file, 'utf8');
    for (const match of text.matchAll(/from\s+['"](\.[^'"]+)['"]/g)) {
      const target = resolve(dirname(file), match[1]) + '.ts';
      if (existsSync(target)) queue.push(target);
    }
  }
  return [...seen].sort();
}

function rewriteRelativeImports(code) {
  return code.replace(
    /((?:from\s+|import\s*\(\s*)['"])(\.[^'"]+)(['"])/g,
    (_whole, prefix, specifier, suffix) => {
      if (/\.(mjs|js|json)$/.test(specifier)) return prefix + specifier + suffix;
      return prefix + specifier + '.mjs' + suffix;
    },
  );
}

// Transpile the closure into a throwaway directory and import the entry
// modules. Returns the loaded modules plus a cleanup function that
// removes the throwaway directory (the returned data is plain values
// by then, so cleanup is safe immediately after extraction).
export async function loadWalletSources() {
  const cacheDir = join(APP_DIR, 'node_modules', '.cache');
  if (!existsSync(cacheDir)) {
    fail(
      'apps/web/node_modules is missing — run `npm ci` in apps/web first ' +
        '(the generator loads the wallet sources through the TypeScript ' +
        'compiler in apps/web/node_modules).',
    );
  }
  let typescript;
  try {
    const require = createRequire(join(SCRIPT_DIR, 'generate-android-registry.mjs'));
    typescript = require('typescript');
  } catch {
    fail(
      'cannot load `typescript` from apps/web/node_modules — run `npm ci` ' +
        'in apps/web first.',
    );
  }
  const tmpDir = mkdtempSync(join(cacheDir, 'android-registry-'));
  try {
    const files = collectClosure(WALLET_SOURCES);
    for (const file of files) {
      const rel = relative(APP_DIR, file).replace(/\.ts$/, '.mjs');
      const out = join(tmpDir, rel);
      mkdirSync(dirname(out), { recursive: true });
      const text = readFileSync(file, 'utf8');
      const result = typescript.transpileModule(text, {
        compilerOptions: {
          module: typescript.ModuleKind.ESNext,
          target: typescript.ScriptTarget.ES2022,
        },
        fileName: file,
      });
      writeFileSync(out, rewriteRelativeImports(result.outputText), 'utf8');
    }
    const importModule = (rel) =>
      import(pathToFileURL(join(tmpDir, rel)).href);
    const chains = await importModule(join('src', 'wallet', 'chains.mjs'));
    const expanded = await importModule(join('src', 'wallet', 'chains-expanded.mjs'));
    const tokens = await importModule(join('src', 'wallet', 'tokens.mjs'));
    const tokenPrices = await importModule(join('src', 'wallet', 'token-prices.mjs'));
    const prices = await importModule(join('src', 'wallet', 'prices.mjs'));
    const priceFallbacks = await importModule(join('src', 'wallet', 'price-fallbacks.mjs'));
    const dexPrices = await importModule(join('src', 'wallet', 'dex-prices.mjs'));
    const chainAmountFormat = await importModule(
      join('src', 'wallet', 'chain-amount-format.mjs'),
    );
    const devnet = await importModule(join('src', 'wallet', 'devnet-endpoints.mjs'));
    const watchOnly = await importModule(join('src', 'wallet', 'watch-only-families.mjs'));
    return {
      chains,
      expanded,
      tokens,
      tokenPrices,
      prices,
      priceFallbacks,
      dexPrices,
      chainAmountFormat,
      devnet,
      watchOnly,
      cleanup() {
        rmSync(tmpDir, { recursive: true, force: true });
      },
    };
  } catch (error) {
    rmSync(tmpDir, { recursive: true, force: true });
    throw error;
  }
}

