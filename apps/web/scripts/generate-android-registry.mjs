// Generate the Android registry export (registry/chains.json and
// registry/tokens.json) from the web wallet's TypeScript sources.
//
// Usage (from the repo root or from apps/web):
//   node apps/web/scripts/generate-android-registry.mjs           rewrite the JSON files
//   node apps/web/scripts/generate-android-registry.mjs --check   exit 1 when the JSON files drift
//
// Direction: the web wallet is the source of truth. The generator reads
// the evaluated TS modules (CHAINS, EXPANDED_CHAINS, DEFAULT_TOKENS,
// PRICE_IDS, CHAIN_DECIMALS, price fallbacks, devnet endpoints) and the
// registry/capabilities.json coins table, and writes versioned JSON any
// non-TypeScript consumer (first of all the Android app) can read.
// Generated, never hand-edited: each JSON file carries a generated
// notice plus the source commit the data was read at.
//
// Method: the TS modules are loaded by transpiling them with the
// TypeScript compiler API (typescript is a direct devDependency of
// @bawa/web — no new dependency, no network, no esbuild/vite) into a
// throwaway directory under apps/web/node_modules/.cache, then
// importing the entry modules. Loading the real modules means the
// export reads the real values — including the evaluated pathFor
// functions and priceFallbackSourcesFor — instead of a re-implementation
// that could drift. Two maps are module-private in the sources, so
// they are extracted textually with strict parsers (COINBASE_PRODUCT_IDS
// in price-fallbacks.ts, CHAIN_PATTERNS in address-detection.ts); the
// tests pin their counts so a silent shape change fails loudly.
//
// Cross-checks: every value that exists in two sources is compared and
// any disagreement fails the run (CHAINS vs EXPANDED_CHAINS RPCs,
// explorers, CoinGecko ids and derivation templates; CHAIN_DECIMALS vs
// the coins table; EXPANDED coinType vs the coins table coinId;
// CoinLore/Coinbase/DexScreener maps vs the expanded price sources;
// chains.json ids vs capabilities.json chainSupport, both directions).
// Nothing is invented: a value the sources do not record is null with
// a note naming the gap (see the per-entry `notes` field and the
// coverage block). Two SLIP-44 numbers are emitted per chain and must
// not be conflated: coinType is the coin the derivation path derives
// from (60 for EVM chains on the Ethereum path); assetSlip44 is the
// chain's registered number from its assetId (714 for BSC, 966 for
// Polygon, 9000 for Avalanche, 527 for Celo, 250 for Fantom). Where
// they differ the entry carries a note. The live CHAINS capabilities
// are compared against capabilities.json chainSupport and any
// divergence is printed as a warning — the export itself carries no
// capability claims.
//
// The --check comparison ignores `generatedAt` (a wall-clock timestamp
// would make every regeneration look like drift); everything else,
// including `sourceCommit` and `sourceDirty`, must match byte for byte
// after JSON round-tripping. `sourceCommit` is the last commit that
// touched any data source file, so unrelated commits do not stale the
// export; `sourceDirty` records uncommitted changes in those files.
