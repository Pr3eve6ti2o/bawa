// Coins-table mapping (registry/capabilities.json `coins` -> chain id)
// ---------------------------------------------------------------------------

// Map each coins entry to a chain id. Rules, in order:
// 1. bawaChainId when the entry is supported (the registry says so);
// 2. an exact displayName match against exactly one chain;
// 3. a coinTypeName match (case-insensitive) against exactly one chain.
// A rule that matches zero chains falls through; a rule that matches
// more than one fails loudly — an ambiguous mapping must never be
// guessed. Returns { byRegistryId, chainsWithoutCoins }.
export function mapCoinsToChains(coins, chainIds, displayNames, coinTypeNames) {
  const byDisplayName = new Map();
  const byCoinTypeName = new Map();
  for (const chain of chainIds) {
    const displayName = displayNames.get(chain);
    if (displayName !== undefined) {
      if (!byDisplayName.has(displayName)) byDisplayName.set(displayName, []);
      byDisplayName.get(displayName).push(chain);
    }
    const coinTypeName = (coinTypeNames.get(chain) ?? '').toLowerCase();
    if (coinTypeName !== '') {
      if (!byCoinTypeName.has(coinTypeName)) byCoinTypeName.set(coinTypeName, []);
      byCoinTypeName.get(coinTypeName).push(chain);
    }
  }
  const byRegistryId = new Map();
  const errors = [];
  for (const [registryId, entry] of Object.entries(coins)) {
    let chain;
    let rule;
    if (typeof entry.bawaChainId === 'string' && entry.bawaChainId !== '') {
      chain = entry.bawaChainId;
      rule = 'bawaChainId';
      if (!chainIds.includes(chain)) {
        errors.push(`coins.${registryId}: bawaChainId '${chain}' is not a supported chain`);
        continue;
      }
    } else {
      const displayHits = byDisplayName.get(entry.displayName) ?? [];
      if (displayHits.length === 1) {
        chain = displayHits[0];
        rule = 'displayName';
      } else if (displayHits.length > 1) {
        errors.push(
          `coins.${registryId}: displayName '${entry.displayName}' matches more than one chain (${displayHits.join(', ')})`,
        );
        continue;
      } else {
        const nameHits = byCoinTypeName.get((entry.coinTypeName ?? '').toLowerCase()) ?? [];
        if (nameHits.length === 1) {
          chain = nameHits[0];
          rule = 'coinTypeName';
        } else if (nameHits.length > 1) {
          errors.push(
            `coins.${registryId}: coinTypeName '${entry.coinTypeName}' matches more than one chain (${nameHits.join(', ')})`,
          );
          continue;
        } else {
          errors.push(
            `coins.${registryId}: no chain matches displayName '${entry.displayName}' or coinTypeName '${entry.coinTypeName}'`,
          );
          continue;
        }
      }
    }
    if (byRegistryId.has(chain)) {
      errors.push(
        `coins.${registryId}: chain '${chain}' is already claimed by coins.${byRegistryId.get(chain).registryId}`,
      );
      continue;
    }
    byRegistryId.set(registryId, { chain, rule, entry });
  }
  if (errors.length > 0) fail(`coins-table mapping failed:\n${errors.join('\n')}`);
  const mappedChains = new Set([...byRegistryId.values()].map((value) => value.chain));
  return {
    byRegistryId,
    chainsWithoutCoins: chainIds.filter((chain) => !mappedChains.has(chain)),
  };
}

