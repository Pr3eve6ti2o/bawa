function gitInfo() {
  const run = (args) => {
    try {
      return execFileSync('git', args, {
        cwd: REPO_DIR,
        encoding: 'utf8',
        stdio: ['ignore', 'pipe', 'ignore'],
      }).trim();
    } catch {
      return null;
    }
  };
  const sourceArgs = DATA_SOURCE_FILES.map((file) => relative(REPO_DIR, file));
  const sourceCommit = run(['log', '-1', '--format=%H', '--', ...sourceArgs]) || null;
  const status = run(['status', '--porcelain', '--', ...sourceArgs]);
  return {
    sourceCommit,
    sourceDirty: status === null ? null : status !== '',
  };
}

// ---------------------------------------------------------------------------
// JSON Schema validation (subset: the constructs the schemas use)
// ---------------------------------------------------------------------------

function resolveRef(root, ref) {
  if (!ref.startsWith('#/')) {
    fail(`schema validation: unsupported $ref '${ref}'`);
  }
  let node = root;
  for (const part of ref.slice(2).split('/')) {
    node = node[part.replace(/~1/g, '/').replace(/~0/g, '~')];
    if (node === undefined) fail(`schema validation: cannot resolve $ref '${ref}'`);
  }
  return node;
}

function typeMatches(value, type) {
  switch (type) {
    case 'string':
      return typeof value === 'string';
    case 'integer':
      return Number.isSafeInteger(value);
    case 'number':
      return typeof value === 'number' && Number.isFinite(value);
    case 'boolean':
      return typeof value === 'boolean';
    case 'array':
      return Array.isArray(value);
    case 'object':
      return isPlainObject(value);
    case 'null':
      return value === null;
    default:
      return false;
  }
}

// Validate a value against a schema document. Returns the list of
// violations (empty when valid). Supports $ref, type (incl. arrays of
// types), required, properties, additionalProperties, enum, minLength,
// minimum, pattern, items, minItems, format date-time/uri.
export function validateAgainstSchema(doc, schema) {
  const errors = [];
  const check = (value, node, label) => {
    if (node.$ref !== undefined) {
      check(value, resolveRef(schema, node.$ref), label);
      return;
    }
    if (node.type !== undefined) {
      const types = Array.isArray(node.type) ? node.type : [node.type];
      if (!types.some((type) => typeMatches(value, type))) {
        errors.push(`${label}: expected type ${types.join(' | ')}, found ${Array.isArray(value) ? 'array' : typeof value}`);
        return;
      }
    }
    if (node.enum !== undefined && !node.enum.includes(value)) {
      errors.push(`${label}: value ${JSON.stringify(value)} is not in enum [${node.enum.join(', ')}]`);
    }
    if (typeof value === 'string') {
      if (node.minLength !== undefined && value.length < node.minLength) {
        errors.push(`${label}: string shorter than minLength ${node.minLength}`);
      }
      if (node.pattern !== undefined && !new RegExp(node.pattern).test(value)) {
        errors.push(`${label}: string ${JSON.stringify(value)} does not match pattern ${node.pattern}`);
      }
      if (node.format === 'date-time' && Number.isNaN(Date.parse(value))) {
        errors.push(`${label}: string ${JSON.stringify(value)} is not a date-time`);
      }
      if (node.format === 'uri') {
        try {
          const url = new URL(value);
          if (url.protocol !== 'https:' && url.protocol !== 'http:') {
            errors.push(`${label}: URI ${JSON.stringify(value)} is not http(s)`);
          }
        } catch {
          errors.push(`${label}: string ${JSON.stringify(value)} is not a URI`);
        }
      }
    }
    if (typeof value === 'number' && node.minimum !== undefined && value < node.minimum) {
      errors.push(`${label}: ${value} is below minimum ${node.minimum}`);
    }
    if (Array.isArray(value)) {
      if (node.minItems !== undefined && value.length < node.minItems) {
        errors.push(`${label}: array has fewer than minItems ${node.minItems} items`);
      }
      if (node.items !== undefined) {
        value.forEach((item, index) => check(item, node.items, `${label}[${index}]`));
      }
    }
    if (isPlainObject(value) && node.properties !== undefined) {
      for (const field of node.required ?? []) {
        if (!Object.prototype.hasOwnProperty.call(value, field)) {
          errors.push(`${label}: missing required field '${field}'`);
        }
      }
      for (const [field, fieldSchema] of Object.entries(node.properties)) {
        if (Object.prototype.hasOwnProperty.call(value, field)) {
          check(value[field], fieldSchema, `${label}.${field}`);
        }
      }
      if (node.additionalProperties === false) {
        for (const field of Object.keys(value)) {
          if (!Object.prototype.hasOwnProperty.call(node.properties, field)) {
            errors.push(`${label}: unexpected field '${field}'`);
          }
        }
      }
    }
  };
  check(doc, schema, '$');
  return errors;
}

function loadJson(path, label) {
  try {
    return JSON.parse(readFileSync(path, 'utf8'));
  } catch (error) {
    fail(`cannot read ${label} at ${path}: ${error.message}`);
  }
}

function httpsUrl(value, label, errors) {
  if (typeof value !== 'string') {
    errors.push(`${label}: expected a string, found ${typeof value}`);
    return;
  }
  let url;
  try {
    url = new URL(value);
  } catch {
    errors.push(`${label}: '${value}' is not a URL`);
    return;
  }
  if (url.protocol !== 'https:') {
    errors.push(`${label}: '${value}' is not an https: URL`);
  }
}

