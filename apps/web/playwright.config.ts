// Playwright config for the critical-path E2E harness (repo-study
// Phase 3, item 27).
//
// The harness drives the built app (vite preview of dist/) in Chromium
// only. The driver owns the server and the browser lifecycle: the
// webServer block starts `npm run preview` and waits for it, so a test
// never runs against a stale or hand-started server.
//
// Security boundaries (enforced by the specs in e2e/, see
// e2e/manifest.json):
// - No tracing, ever: a trace would record the recovery phrase and the
//   vault password as they are typed. trace is 'off' here and no spec
//   may enable it.
// - No video: same reason.
// - Failure screenshots mask every secret-bearing region (the phrase
//   grid, the confirm-words inputs, any password input) before the
//   screenshot is taken.
// - Every wallet used by a spec is disposable: a fresh vault password
//   generated per run, a fresh mnemonic generated by the app itself,
//   never a production or existing phrase, never funded.
import { defineConfig, devices } from '@playwright/test';

const isCI = !!process.env.CI;

export default defineConfig({
  testDir: './e2e',
  timeout: 30_000,
  expect: { timeout: 5_000 },
  // Continue after a failure: one broken case must not hide the rest.
  // The verdict is machine-enforced — the suite exits non-zero unless
  // every case passes (see manifest.json).
  fullyParallel: false,
  workers: 1,
  retries: isCI ? 1 : 0,
  reporter: isCI ? [['list'], ['html', { open: 'never' }]] : 'list',
  use: {
    baseURL: 'http://127.0.0.1:4193',
    trace: 'off',
    video: 'off',
    // No automatic failure screenshots: Playwright cannot mask regions
    // in automatic shots, and a shot of the create flow would capture
    // the recovery phrase. Specs capture failure evidence themselves
    // via the masked afterEach helper in e2e/helpers.ts.
    screenshot: 'off',
  },
  projects: [
    {
      name: 'chromium',
      use: { ...devices['Desktop Chrome'] },
    },
  ],
  webServer: {
    // Port 4193 (not Vite's default 4173): other lanes on this shared
    // machine run their own preview on 4173, and reuseExistingServer
    // would otherwise attach the tests to their app.
    // Bind explicitly to 127.0.0.1: bare `vite preview` binds to
    // `localhost`, which can resolve to ::1 while the URL below is IPv4
    // — the server then never answers the health check.
    command: 'npm run preview -- --host 127.0.0.1 --port 4193',
    url: 'http://127.0.0.1:4193',
    reuseExistingServer: !isCI,
    timeout: 120_000,
  },
});
